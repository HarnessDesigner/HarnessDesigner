ZERO_POINT = _point.ZERO_POINT


# Pre-allocated world-up constant — avoids repeated array allocation in
# _calculate_camera() and _rotate_about() which are called on every frame
# and every mouse-drag event respectively.
_WORLD_UP = np.array([0.0, 1.0, 0.0], dtype=np.float32)

# Fixed camera basis -- this camera is permanently locked looking straight
# down the world Y axis (new_canvas2d is dedicated to the flat schematic/
# pegboard views, never a freely-orientable 3D camera), so there is no
# per-frame cross-product basis derivation needed at all. Chosen so world
# X maps to screen X and world Z maps to screen Y, using the same
# right = cross(world_up, forward) / up = cross(forward, right) convention
# gl.canvas3d.camera.Camera's own locked top-down mode uses (verified:
# cross(_FORWARD, _RIGHT) == _UP).
_FORWARD = np.array([0.0, -1.0, 0.0], dtype=np.float32)
_RIGHT = np.array([1.0, 0.0, 0.0], dtype=np.float32)
_UP = np.array([0.0, 0.0, 1.0], dtype=np.float32)


class CameraBase:

    __doc__ = __doc__

    @_check_types.do
    def __init__(self, canvas: "_canvas_base.CanvasBase"):
        """
        Initialise the :class:`Camera` instance.

        :param canvas: Canvas instance.
        :type canvas: :class:`_canvas_base.CanvasBase`
        """

        self.canvas = canvas
        self._camera_moved_since_last_cull = True

        self._is_dirty = True
        self._projection = None
        self._modelview = None
        self._viewport = None
        self._clip = None
        self._inv_clip = None
        self._fov = None
        self._up = None
        self._right = None
        self._forward = None

        self._frustum_planes = None
        self._frustum_normals = None
        self._frustum_distances = None

        self._target = None

        self._focal_position = _point.Point(0.0, self.canvas.config.floor.ground_height + 10.0, 0.0)
        self._position = _point.Point(0.0, self.canvas.config.floor.ground_height + 100.0, 75.0)
        self._angle = _angle.Angle.from_points(self._position, self._focal_position)
        self._angle_from_center = _angle.Angle.from_points(ZERO_POINT.copy(), self._position)
        self._focal_distance = _line.Line(self._position, self._focal_position).length()
        self._distance_from_center = _line.Line(ZERO_POINT, self._position).length()

        # Set around the FIRST of a rigid dual-write to both _position
        # and _focal_position together (Dolly/TruckPedestal/Walk/
        # CenterOn -- both move by the same delta, so they're really one
        # logical "moved the rig" event) -- checked by _update_camera
        # itself, below, so its own internal recompute runs only once
        # per such move (on the second write) instead of twice, WITHOUT
        # suppressing anything else bound to _position (see this
        # attribute's own history: the previous approach wrapped the
        # first write in `with self._position:`, which -- via
        # CallbackMixin's own __ref_count__ batching guard -- silently
        # drops EVERY callback bound to _position for that write, not
        # just this class's own internal one. shapes.text's own camera-
        # tracking update, bound directly to a 3D camera's .position,
        # was the first thing to ever actually depend on that write
        # firing and surfaced this).
        self._updating_rig: bool = False

        self._calculate_camera()
        self._position.bind(self._update_camera)
        self._focal_position.bind(self._update_camera)

    @property
    @_check_types.do
    def field_of_view(self) -> float:
        """
        Return the field of view.

        Populated by set_view() the first time the canvas's own
        _set_view() runs; 0.0 before that.

        :rtype: float
        """
        if self._fov is None:
            return 0.0

        return self._fov

