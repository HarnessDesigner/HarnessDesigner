    @_check_types.do
    def _send_event(self, type_):
        event = _events.GLCameraEvent.from_canvas(type_, self.canvas)

        if event is None:
            return

        getattr(self.canvas, event.GetType()).emit(event)

        self._refresh_active_hover()

    @_check_types.do
    def _refresh_active_hover(self) -> None:
        """Re-run the active wire-placement handler's hover(), or the
        active drag's own pick-test, using the current mouse position --
        called every time this camera's own state changes (see
        _send_event, the one place every movement method -- Reset,
        Rotate, PanTilt, Zoom, Walk, TruckPedestal -- already funnels
        through, so hooking it here covers all of them from one spot).

        A camera move can happen with the mouse held perfectly still --
        the mouse wheel's zoom (plus its own auto-reorient-toward-mouse
        turn) and every keyboard-driven camera control in key_handler.py
        both change the camera without ever going through
        on_mouse_motion. Without this, an active AddWireHandler's preview
        wire, or a snapped EndpointDragObject, would keep reflecting
        wherever the mouse last actually moved under the OLD camera
        framing until the next real pixel of mouse movement -- stale and
        potentially misleading about what's actually under the cursor
        now. QCursor.pos() (mapped to widget-local coordinates, the same
        way key_handler.py's own _send_event already derives a position
        for key events, which don't carry one) gives the current mouse
        position without needing to cache the last real motion event.

        self.set() runs first so a handler's own hover math (e.g.
        get_position_on_focal_plane/UnprojectPoint, both used by
        placement handlers to track the mouse across the focal plane)
        reads THIS move's forward/focal_distance/view matrices, not
        whatever the last real _on_draw() paint frame left cached --
        this call happens well before that next paint, otherwise it
        would still be one frame stale (see canvas_3d.camera.Camera.set
        for why a plain camera move doesn't already guarantee this).
        """
        target = self.canvas.active_handler_obj
        if target is None:
            return

        mouse_handler = self.canvas._mouse_handler  # NOQA
        if mouse_handler is None:
            return

        self.set()

        from PySide6.QtGui import QCursor

        local_pos = self.canvas.mapFromGlobal(QCursor.pos())
        mouse_pos = _point.Point(float(local_pos.x()), float(local_pos.y()))

        mouse_handler._dispatch_to_active_handler(  # NOQA
            mouse_pos, _interaction.MouseInteraction.MOVE, mouse_handler._is_motion)  # NOQA

    @property
    @_check_types.do
    def aspect_ratio(self) -> float:
        """
        Return the aspect ratio.

        :rtype: float
        """
        if self._viewport is None or self._viewport[3] == 0:
            return 1.0

        return float(self._viewport[2]) / float(self._viewport[3])

    @_check_types.do
    def Reset(self):
        """
        Reset the camera back to its home position -- directly above the
        origin, looking straight down (this camera is permanently locked
        to that pose, see _FORWARD/_RIGHT/_UP above).
        """
        with self._position, self._focal_position:
            self._focal_position.x = 0.0
            self._focal_position.y = self.canvas.config.floor.ground_height + 10.0
            self._focal_position.z = 0.0

            self._position.x = 0.0
            self._position.y = self.canvas.config.floor.ground_height + 100.0
            self._position.z = 0.0

        self._update_camera(None)
        self._send_event(_events.EVT_GL_CAMERA_RESET)

    @_check_types.do
    def _update_camera(self, _=None):
        """
        Update the camera.

        :type _: None
        """
        if self._updating_rig:
            # The first of a rigid dual-write to _position AND
            # _focal_position together -- see _updating_rig's own
            # comment in __init__. The second write (whichever method
            # is currently running clears the flag before making it)
            # runs this in full, covering both changes at once.
            return

        self._camera_moved_since_last_cull = True

        if (
            self.canvas.config.floor.enable_floor_lock and
            self._position.y < self.canvas.config.floor.ground_height + 0.05
        ):
            with self._position:
                self._position.y = self.canvas.config.floor.ground_height + 0.25

        self._is_dirty = True

        _app.CallAfter(self.canvas.update)

    @property
    @_check_types.do
    def has_camera_moved(self) -> bool:
        """
        Has the camera moved.

        :returns: If the camera has moved
        :rtype: bool
        """
        res = self._camera_moved_since_last_cull
        self._camera_moved_since_last_cull = False
        return res

    @property
    @_check_types.do
    def is_dirty(self) -> bool:
        """
        Whether the camera's cached view/projection/clip/frustum data is
        stale and needs rebuilding via :meth:`set_view`.

        Set whenever position/focal_position actually change (the only
        things that ever move the camera -- the mouse/key handlers).
        Consumers should treat this as a failsafe check, not rebuild
        unconditionally every frame: the canvas render surface is a fixed
        virtual size that never changes from a plain window resize (see
        MEMORY.md), so a camera move is genuinely the only thing that
        should trigger a rebuild.

        :rtype: bool
        """
        return self._is_dirty

    @staticmethod
    @_check_types.do
    def _extract_frustum_planes(view_proj: np.ndarray) -> np.ndarray:
        """
        Returns planes as an array shape (6,4): [A,B,C,D] per plane.

        Planes are normalized (A,B,C length = 1).

        Order: left, right, bottom, top, near, far

        :type view_proj: :class:`np.ndarray`

        :rtype: :class:`np.ndarray`
        """

        m = np.asarray(view_proj, dtype=np.float32)

        # rows
        r0 = m[0, :]
        r1 = m[1, :]
        r2 = m[2, :]
        r3 = m[3, :]

        planes = np.stack([(r3 + r0),  # left
                          (r3 - r0),  # right
                          (r3 + r1),  # bottom
                          (r3 - r1),  # top
                          (r3 + r2),  # near  (OpenGL style)
                          (r3 - r2),  # far
                           ], axis=0)

        # normalize planes
        n = np.linalg.norm(planes[:, 0:3], axis=1)
        planes = planes / n[:, None]

        return planes

    @_check_types.do
    def set(self):
        """
        Refresh the camera's own basis vectors (forward/right/up) from its
        current position/focal_position, but only when something actually
        moved since the last call.

        Pure local math, gated on :attr:`is_dirty` -- no OpenGL, and no
        call into the canvas. Building/applying the view or projection
        matrix is entirely the rendering pipeline's job (each canvas's own
        `_set_view()`, called from its `_on_draw()`) -- this method never
        triggers that, directly or indirectly.
        """

        if not self._is_dirty:
            return

        self._calculate_camera()

    @_debug.logfunc
    @_check_types.do
    def _calculate_camera(self):
        """
        Calculate the camera.
        """

        pos = self._position.as_numpy
        fp = self._focal_position.as_numpy

        forward = fp - pos

        focal_distance = np.linalg.norm(forward)
        if focal_distance < 1e-6:
            return

        forward = forward / focal_distance

        world_up = _WORLD_UP.copy()
        dot = float(np.dot(forward, world_up))

        # When the view direction gets too close to the world-up vector the
        # look-at basis becomes ill-conditioned. Preserve the previous camera up
        # vector in that case so zooming through very small focal distances does
        # not cause a sudden 90° roll.
        if abs(dot) > 0.9999 and self._up is not None:
            up = np.array(self._up, dtype=np.float32)
            un = np.linalg.norm(up)
            if un < 1e-6:
                up = world_up.copy()
                # un = 1.0
            else:
                up = up / un

            right = np.cross(forward, up)  # NOQA
            rn = np.linalg.norm(right)
            if rn < 1e-6:
                fallback_axis = np.array([1.0, 0.0, 0.0], dtype=np.float32)
                if abs(float(np.dot(forward, fallback_axis))) > 0.9999:
                    fallback_axis = np.array([0.0, 0.0, 1.0], dtype=np.float32)

                right = np.cross(fallback_axis, forward)  # NOQA
                rn = np.linalg.norm(right)

            right = right / rn
            up = np.cross(right, forward)  # NOQA
            un = np.linalg.norm(up)
            up = up / (un if un >= 1e-6 else 1.0)
        else:
            right = np.cross(world_up, forward)  # NOQA

            rn = np.linalg.norm(right)
            if rn < 1e-6:
                right = np.array([1.0, 0.0, 0.0], dtype=np.float32)
                # rn = 1.0
            else:
                right = right / rn

            up = np.cross(forward, right)  # NOQA

            un = np.linalg.norm(up)
            if un < 1e-6:
                up = world_up.copy()
                # un = 1.0
            else:
                up = up / un

        # self._forward_norm = focal_distance
        # self._right_norm = rn
        # self._up_norm = un

        self._up = up
        self._right = right
        self._forward = forward

        self._focal_distance = focal_distance

    @_check_types.do
    def set_view(self, projection: np.ndarray, modelview: np.ndarray,
                 fov: float | None = None) -> None:
        """
        Store the projection/modelview matrices the canvas's own
        :meth:`~gl.canvas_base.canvas_base.CanvasBase._set_view` override
        just computed -- perspective for the 3D canvas, orthographic for
        schematic/pegboard, the camera itself has no opinion on which --
        and derive the viewport/clip/frustum data used elsewhere
        (picking, culling, ProjectPoint/UnprojectPoint) from them.

        No OpenGL calls: *projection*/*modelview* were already built
        locally by the caller, and everything derived here is plain
        matrix algebra on them.

        :param projection: Row-major projection matrix (for
            ``matrix @ column_vector``), as built by the canvas.
        :type projection: :class:`np.ndarray`

        :param modelview: Row-major view matrix, as built by the canvas.
        :type modelview: :class:`np.ndarray`

        :param fov: The vertical field of view (degrees) the caller built
            *projection* with -- the canvas already knows this value, so
            it's passed through directly rather than reverse-derived from
            the matrix. Leave ``None`` for an orthographic view, which
            has no field of view.
        :type fov: float | None
        """

        self._projection = projection
        self._modelview = modelview
        self._fov = fov

        if self.canvas.size:
            w, h = self.canvas.size
        else:
            w = self.canvas.width()
            h = self.canvas.height()

        self._viewport = np.array([0, 0, w, h], dtype=np.int32)

        self._clip = (self._projection @ self._modelview).astype(np.float32)

        # Cache the inverse -- avoids recomputing it in every
        # UnprojectPoint / get_position_on_focal_plane call this frame.
        self._inv_clip = np.linalg.inv(self._clip)

        self._frustum_planes = self._extract_frustum_planes(self._clip)

        # Pre-extract normals and distances for faster AABB checking
        self._frustum_normals = np.ascontiguousarray(
            self._frustum_planes[:, 0:3])

        self._frustum_distances = np.ascontiguousarray(
            self._frustum_planes[:, 3])

        self._is_dirty = False

    @_debug.logfunc
    @_check_types.do
    def Rotate(self, dx: int | float, dy: int | float):
        """
        Moves the camera position keeping the focused point locked.

        :param dx: Mouse delta X coordinate.
        :type dx: int

        :param dy: Mouse delta Y coordinate.
        :type dy: int
        """

        self._is_dirty = True
        position = self._rotate_about(
            dx, dy, self._position, self._focal_position)

        self._position += position - self._position
        self._send_event(_events.EVT_GL_CAMERA_ORBIT)

    @staticmethod
    @_debug.logfunc
    @_check_types.do
    def _rotate_about(dx: int | float, dy: int | float,
                      p1: _point.Point, p2: _point.Point) -> _point.Point:
        """
        Moves the camera position keeping the focused point locked.
        """

        # This is a constant that can be adjusted. This is a hard limit
        # to prevent gimbal lock from occuring when looking straight up or
        # straight down. You can set it to a smaller number but do not increase
        # it past 89.9 otherwise gimbal lock can occur.
        p1_np = p1.as_numpy
        p2_np = p2.as_numpy

        max_pitch = 89.9

        offset = p1_np - p2_np
        dist = np.linalg.norm(offset)

        if dist < 1e-6:
            return _point.Point(0.0, 0.0, 0.0)

        up = _WORLD_UP.copy()

        @_check_types.do
        def _rodrigues(v, k, angle_rad):
            """
            Execute the rodrigues operation.

            UNKNOWN details are inferred from the callable name and signature.

            :param v: Value for ``v``.
            :param k: Value for ``k``.
            :param angle_rad: Value for ``angle_rad``.
            :returns: Return value. UNKNOWN details.
            """

            k = k / np.linalg.norm(k)

            cos_a = math.cos(angle_rad)
            sin_a = math.sin(angle_rad)  # NOQA

            return ((v * cos_a) + (np.cross(k, v) * sin_a) +  # NOQA
                    (k * np.dot(k, v) * (1.0 - cos_a)))

        yaw_offset = _rodrigues(offset, up, math.radians(dx))
        yaw_offset_n = np.linalg.norm(yaw_offset)

        if yaw_offset_n < 1e-6:
            return _point.Point(0.0, 0.0, 0.0)

        yaw_dir = yaw_offset / yaw_offset_n

        horiz_len = math.hypot(yaw_dir[0], yaw_dir[2])

        cur_pitch_deg = math.degrees(math.atan2(yaw_dir[1], horiz_len))

        desired_pitch = cur_pitch_deg + dy
        if desired_pitch > max_pitch or desired_pitch < -max_pitch:
            # block pitch movement entirely (yaw still applies)
            dy = 0.0

        if abs(dy) < 1e-6:
            final_offset = yaw_dir * dist
        else:
            right = np.cross(yaw_dir, up)  # NOQA
            rn = np.linalg.norm(right)

            if rn < 1e-6:
                final_offset = yaw_dir * dist
            else:
                right = right / rn
                rotated = _rodrigues(yaw_offset, right, math.radians(dy))

                rnorm = np.linalg.norm(rotated)

                if rnorm < 1e-6:
                    final_offset = yaw_dir * dist
                else:
                    # explicitly restore original distance to avoid shrink/grow
                    final_offset = rotated * (dist / rnorm)

        new_point = p2_np + final_offset

        return _point.Point(new_point[0], new_point[1], new_point[2])

    @_debug.logfunc
    @_check_types.do
    def PanTilt(self, dx: int | float, dy: int | float):
        """
        Pan and Tilt camera movements.

        Moves the camera center keeping the camera eye locked in place.

        :param dx: Mouse delta X coordinate.
        :type dx: int

        :param dy: Mouse delta Y coordinate.
        :type dy: int
        """

        self._is_dirty = True
        focal_point = self._rotate_about(
            dx, dy, self._focal_position, self._position)

        self._focal_position += focal_point - self._focal_position
        self._send_event(_events.EVT_GL_CAMERA_ROTATE)

    @_debug.logfunc
    @_check_types.do
    def Zoom(self, delta, *_):
        """
        This has a similiar movement appearance as Dolly except there are hard
        limits as to how far it is able to move where as Dolly does not.
        This also doesn't change the camera position at all. It simply shinks
        or expands the distance between the focal point and the camera eye.

        :param delta: Amount to zoom.
        :type delta: float
        """

        delta = -delta

        min_distance = 0.1
        max_distance = 500.0

        offset = self._focal_position.as_numpy - self._position.as_numpy
        current_distance = np.linalg.norm(offset)
        if current_distance < 1e-6:
            return

        target_distance = current_distance - float(delta)

        if target_distance < min_distance:
            target_distance = min_distance
        elif target_distance > max_distance:
            target_distance = max_distance

        move_distance = current_distance - target_distance
        if abs(move_distance) < 1e-9:
            return

        move = self._forward * move_distance

        self._is_dirty = True
        self._focal_position += move

        self._send_event(_events.EVT_GL_CAMERA_ZOOM)

    @_debug.logfunc
    @_check_types.do
    def Walk(self, dx: int | float, dy: int | float, speed: float):
        """
        This movement is a bit tricky to explain in terms of camera movement.
        If you think about what you do as a person when you walk this will
        mimick as close as I could get to that movement. so basically if you
        want to walk straight forward and back you get that from this function.
        That is the same as a Dolly camera movement.

        if you go left and right the movement you get is as if you are turning
        on the ball of your foot. This is comparable to the "Pan" movement of a
        camera.

        If you hold left or right and press up or down at the same time you get
        a combination of the 2 above movements. kind of like what it would be
        like when you walk in an arc to either left or right.

        :param dx: Mouse delta X coordinate.
        :type dx: int

        :param dy: Mouse delta Y coordinate.
        :type dy: int

        :param speed: Speed to move.
        :type speed: float
        """

        # Build desired move from input
        # input_mag = math.sqrt((dx * dx) + (dy * dy))
        input_mag = math.hypot(dx, dy)

        if input_mag == 0:
            return

        move_dir = self._right * float(dx) + self._forward * float(dy)

        mdn = np.linalg.norm(move_dir)

        if mdn < 1e-6:
            return

        move_dir = move_dir / mdn
        move = move_dir * (input_mag * speed)

        self._is_dirty = True

        self._updating_rig = True
        self._position += move
        self._updating_rig = False

        self._focal_position += move

        self._send_event(_events.EVT_GL_CAMERA_WALK)

    @_debug.logfunc
    @_check_types.do
    def Dolly(self, distance: int | float):
        """
        Rigid forward/back translation of the whole camera rig -- both
        position and focal_position move together by the same amount
        along the current forward vector, so the distance between them
        (focal_distance) never changes. This is different from
        :meth:`Zoom`, which only moves position (stretching/shrinking
        focal_distance within its own hard clamps), and is the same
        rigid-translation mechanics :meth:`TruckPedestal`/:meth:`Walk`
        use -- in fact it's exactly Walk's straight-ahead case (dx=0)
        minus the turning component Walk mixes in when dx != 0 (see
        Walk's own docstring).

        :param distance: Signed distance to move -- positive moves the
            rig toward the focal point, negative moves it away.
        :type distance: int | float
        """
        if distance == 0:
            return

        move = self._forward * float(distance)

        self._is_dirty = True

        self._updating_rig = True
        self._position += move
        self._updating_rig = False

        self._focal_position += move

        self._send_event(_events.EVT_GL_CAMERA_DOLLY)

    @_debug.logfunc
    @_check_types.do
    def TruckPedestal(self, dx: int | float, dy: int | float, speed: float):
        """
        Truck (left right) and Pedestal (up down).

        :param dx: Mouse delta X coordinate.
        :type dx: int

        :param dy: Mouse delta Y coordinate.
        :type dy: int

        :param speed: Speed to move.
        :type speed: float
        """

        # Build desired move from input
        # input_mag = math.sqrt((dx * dx) + (dy * dy))
        input_mag = math.hypot(dx, dy)

        if input_mag == 0:
            return

        move_dir = self._right * float(dx) + self._up * float(dy)

        mdn = np.linalg.norm(move_dir)
        if mdn < 1e-6:
            return

        move_dir = move_dir / mdn

        move = move_dir * (input_mag * speed)

        self._updating_rig = True
        self._position += move
        self._updating_rig = False

        self._is_dirty = True
        self._focal_position += move

        self._send_event(_events.EVT_GL_CAMERA_TRUCKPEDISTAL)

    @_debug.logfunc
    @_check_types.do
    def CenterOn(self, world_position: _point.Point) -> None:
        """
        Recenter the orbit pivot on *world_position* without changing
        distance, orientation, or zoom -- a rigid translation of the whole
        camera rig (position + focal_position moved by the same delta), the
        same technique :meth:`Walk`/:meth:`TruckPedestal` use for
        mouse-driven moves. Used to bring a selected-but-off-screen object
        into view while disturbing the user's current zoom as little as
        possible.

        :param world_position: World-space point to bring to the focal position.
        :type world_position: :class:`~harness_designer.geometry.point.Point`
        """

        move = world_position.as_numpy - self._focal_position.as_numpy

        self._is_dirty = True

        self._updating_rig = True
        self._position += move
        self._updating_rig = False

        self._focal_position += move

        self._send_event(_events.EVT_GL_CAMERA_WALK)

    @_debug.logfunc
    @_check_types.do
    def ProjectPoint(self, point: _point.Point | np.ndarray) -> _point.Point:
        """
        Projects a 3D world coordinate to a 2D screen coordinate.

        Uses the cached self._clip matrix (projection × modelview) rather
        than performing two separate matrix multiplications.

        :type point: _point.Point | np.ndarray
        :rtype: :class:`_point.Point`
        """

        if isinstance(point, _point.Point):
            world_point = np.array(
                [point.x, point.y, point.z, 1.0], dtype=np.float32)
        else:
            world_point = np.array(
                [point[0], point[1], point[2], 1.0], dtype=np.float32)

        # One matrix multiply instead of two (modelview then projection).
        clip_point = self._clip @ world_point

        if clip_point[3] == 0.0:
            return None

        ndc = clip_point[:3] / clip_point[3]

        screen_x = self._viewport[0] + (ndc[0] + 1.0) * 0.5 * self._viewport[2]
        screen_y = self._viewport[1] + (1.0 - ndc[1]) * 0.5 * self._viewport[3]

        # screen_x = self._viewport[0] + ((ndc[0] + 1.0) * 0.5 * self._viewport[2])
        # screen_y = self._viewport[1] + ((1.0 - ndc[1]) * 0.5 * self._viewport[3])
        screen_z = (ndc[2] + 1.0) * 0.5

        return _point.Point(screen_x, screen_y, screen_z)

    @_debug.logfunc
    @_check_types.do
    def UnprojectPoint(self, point: _point.Point) -> _point.Point:
        """
        Projects a 2D screen coordinate to a 3D world coordinate.

        Uses the cached self._inv_clip matrix rather than recomputing the
        inverse on every call.

        :type point: :class:`_point.Point`
        :rtype: :class:`_point.Point`
        :raises ValueError: Raised when the operation cannot be completed.
        """

        ndc_x = (point.x - self._viewport[0]) / self._viewport[2] * 2.0 - 1.0
        ndc_y = (
            (self._viewport[3] - point.y - self._viewport[1]) /
            self._viewport[3] * 2.0 - 1.0)

        ndc_z = point.z * 2.0 - 1.0

        ndc_point = np.array([ndc_x, ndc_y, ndc_z, 1.0], dtype=np.float32)
        clip_point = self._inv_clip @ ndc_point

        if clip_point[3] == 0.0:
            raise ValueError("Perspective division failed (W=0 in clip space).")

        return _point.Point(*(clip_point[:3] / clip_point[3]))

    @_check_types.do
    def unproject_from_ndc(self, x, y, z):
        """
        ndc: (x,y,z) in [-1,1]
        """

        clip = np.array([x, y, z, 1.0], dtype=np.float32)

        world = self.inv_clip.dot(clip)
        if np.isclose(world[3], 0.0):
            return None

        world /= world[3]
        return world[:3]

    @_check_types.do
    def get_mouse_ray(self, point: _point.Point) -> tuple[np.ndarray, np.ndarray] | tuple[None, None]:
        """Return ``(origin, direction)`` for the world-space ray through
        screen-space *point* -- *origin* is the camera's own eye
        (:attr:`position`), *direction* a normalised unit vector.
        ``(None, None)`` when *point* can't be unprojected (W=0 in clip
        space -- see :meth:`unproject_from_ndc`).

        Depth-independent -- unlike :meth:`get_position_on_focal_plane`,
        which collapses this same ray down to a single point at
        whatever depth the camera's own focal point currently happens
        to be, this hands back the full ray so a caller can measure
        against real geometry at ITS OWN actual depth instead (see
        :meth:`~harness_designer.utils.snap_pool.SnapPool.query_ray`,
        built for exactly this -- a cavity's true position rather than
        an arbitrary focal-plane intersection is what a snap-to-cavity
        session needs to compare against).
        """
        vx, vy, vw, vh = self.viewport

        ndc_x = (2.0 * (point.x - vx) / vw) - 1.0
        ndc_y = (2.0 * (vh - point.y - vy) / vh) - 1.0

        # One unproject — ray origin is the camera position itself
        far_world = self.unproject_from_ndc(ndc_x, ndc_y, 1.0)
        if far_world is None:
            return None, None

        origin = self.position.as_numpy.astype(np.float32)
        direction = np.asarray(far_world, dtype=np.float32) - origin
        norm = np.linalg.norm(direction)
        if norm < 1e-6:
            return None, None

        direction /= norm
        return origin, direction

    @_check_types.do
    def get_position_on_focal_plane(self, point: _point.Point) -> _point.Point:
        origin, direction = self.get_mouse_ray(point)
        if origin is None:
            return self.focal_position.copy()

        # camera.forward  == plane normal (already normalised)
        # camera.focal_distance == dot(focal_pos - origin, plane_normal)
        #                          because forward is the unit vec between them
        denom = np.dot(direction, self.forward)
        if abs(denom) < 1e-6:
            return self.focal_position.copy()

        t = self.focal_distance / denom
        if t < 0:
            return self.focal_position.copy()

        return _point.Point(*(origin + t * direction))

    @_check_types.do
    def closest_point(self, points) -> tuple[int, np.ndarray] | tuple[None, None]:
        """Return (index, point) of whichever of *points* is nearest this
        camera's own eye position -- i.e. whichever one the camera would
        actually see first if the others were occluding candidates at the
        same screen location.

        General-purpose -- usable from anywhere in the app that needs
        "which of these points is actually in front", not just wire
        picking. *points* accepts either shape:

        - A single ``(-1, 3)`` numpy array -- handled as one vectorized
          batch (``np.argmin`` over all rows at once), for callers that
          already have their candidates packed that way.
        - Any number of individual points, each either a `_point.Point`
          or a plain (3,) array/sequence -- for callers building up
          candidates one at a time (e.g. a for loop), no packing needed.

        Ranking only, so distances are compared squared rather than via
        an actual `norm`/sqrt call -- square root is monotonic (a < b iff
        sqrt(a) < sqrt(b) for non-negative a, b), so the nearest-by-
        squared-distance point is always the same one that's nearest by
        real distance too.

        :returns: (None, None) if *points* is empty.
        """
        eye = self.position.as_numpy

        if isinstance(points, np.ndarray):
            if points.shape[0] == 0:
                return None, None

            diffs = points - eye
            dist_sq = np.sum(diffs * diffs, axis=1)
            best_idx = int(np.argmin(dist_sq))

            return best_idx, points[best_idx]

        best_idx = None
        best_point = None
        best_dist_sq = None

        for i, point in enumerate(points):
            p = point.as_numpy if isinstance(point, _point.Point) else np.asarray(point)
            vec = p - eye
            dist_sq = float(np.dot(vec, vec))

            if best_dist_sq is None or dist_sq < best_dist_sq:
                best_dist_sq = dist_sq
                best_idx = i
                best_point = p

        return best_idx, best_point

